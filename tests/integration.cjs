'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
module.exports = async ({ win, runtime, input, state, root, operation, wait, log }) => {
  const report = path.join(root, 'data/integration-report.json');
  const oldError = path.join(root, 'data/integration-error.txt'); if (fs.existsSync(oldError)) fs.unlinkSync(oldError);
  const results = [], mark = (name, detail) => {
    results.push({ name, passed: true, detail }); log('TEST PASS: ' + name);
    fs.writeFileSync(report, JSON.stringify({ time: new Date().toISOString(), results }, null, 2));
  };
  win.webContents.on('console-message', (_event, ...args) => console.log('RENDERER', ...args));
  await win.webContents.executeJavaScript(`(() => {
    const previous = setView;
    setView = view => { console.log('TEST VIEW',view,new Error().stack); return previous(view); };
    document.addEventListener('click',e=>{const nav=e.target.closest('[data-view]');if(nav)console.log('TEST NAV',nav.dataset.view,'trusted='+e.isTrusted);},true);
  })()`);
  await operation('memory', { generation: state.generation, ramMb: 6144 });
  await operation('start');
  let serial = state.serial;
  assert.equal(await runtime.adbRun(['shell', 'getprop', 'sys.boot_completed'], serial), '1');
  mark('真实 Android 14 启动', serial);
  const actualMemory = async () => Number((await runtime.adbRun(['shell', 'cat', '/proc/meminfo'], state.serial)).match(/MemTotal:\s+(\d+)/)[1]);
  const firstMemory = await actualMemory();
  assert.equal(runtime.runningRamMb, 6144); assert.ok(firstMemory > 4 * 1024 * 1024);
  mark('6 GB 默认运存实际生效且超过 4 GB', { configuredMiB: 6144, actualKiB: firstMemory });
  await operation('demo', { generation: state.generation });
  assert.ok((await runtime.adbRun(['shell', 'dumpsys', 'activity', 'activities'], serial)).split('\n').some(l => /ResumedActivity/.test(l) && /com.androiddeck.demo\/.TouchLab/.test(l)));
  await wait(700);
  mark('真实签名 APK 安装与启动', 'com.androiddeck.demo/.TouchLab');
  for (let i = 0; i < 60; i++) {
    const d = await win.webContents.executeJavaScript('window.deckDiagnostics');
    if (d.rendered > 10) break;
    if (i === 59) throw Error('没有解码出真实 Android 视频帧：' + JSON.stringify(d));
    await wait(250);
  }
  const diagnostics = await win.webContents.executeJavaScript('window.deckDiagnostics');
  mark('真实 Android 视频解码', diagnostics);
  const guestFile = '/sdcard/Android/data/com.androiddeck.demo/files/touch-events.jsonl';
  await runtime.adbRun(['shell', 'logcat', '-c'], serial);
  const readEvents = async () => (await runtime.adbRun(['shell', 'cat', guestFile], serial)).split('\n').filter(l => l.startsWith('{')).map(l => JSON.parse(l));
  const focusCanvas = async () => {
    win.show(); win.focus(); win.webContents.focus();
    await win.webContents.executeJavaScript('document.querySelector("[data-view=device]").click();document.getElementById("screen").focus()');
    await wait(300);
    const focus = await win.webContents.executeJavaScript('({active:document.activeElement.id,tag:document.activeElement.tagName,deviceHidden:document.getElementById("device-view").hidden,docFocus:document.hasFocus(),diagnostics:window.deckDiagnostics})');
    console.log('FOCUS',focus); assert.equal(focus.active, 'screen');
  };
  const key = async (keyCode, down) => { win.webContents.sendInputEvent({ type: down ? 'keyDown' : 'keyUp', keyCode }); await wait(100); };
  await focusCanvas();
  await win.webContents.executeJavaScript(`document.addEventListener('keydown', e => console.log('TEST KEY', e.code, e.target.tagName, window.deckDiagnostics.status))`);
  await key('F', true); await key('F', false);
  let events = await readEvents(); assert.deepEqual(events.slice(-2).map(e => e.action), ['DOWN', 'UP']);
  mark('F 点击：Android 收到 DOWN/UP');
  await key('Space', true); await wait(650); await key('Space', false);
  events = await readEvents(); assert.equal(events.at(-1).action, 'UP');
  assert.ok(events.at(-1).time - events.at(-2).time >= 600);
  mark('Space 长按', (events.at(-1).time - events.at(-2).time) + 'ms');
  await key('W', true); await key('D', true); await key('Space', true); await wait(200);
  events = await readEvents(); const two = events.find(e => e.action === 'POINTER_DOWN' && e.count === 2);
  assert.ok(two); assert.equal(new Set(two.pointers.map(p => p.id)).size, 2);
  assert.equal(input.contacts.size, 2);
  mark('W+D 摇杆与 Space 同时产生真实双指', two);
  // Native focus loss exercises both Electron main and renderer safety handlers.
  win.blur(); await wait(250);
  events = await readEvents(); assert.equal(events.at(-1).active, 0); assert.equal(input.contacts.size, 0);
  mark('窗口失焦释放所有触点');
  await key('W', false); await key('D', false); await key('Space', false);
  await operation('mapping-visibility', { visible: false }); await wait(150);
  assert.equal(await win.webContents.executeJavaScript('document.querySelectorAll(".mapping-marker").length'), 0);
  await focusCanvas(); await key('Space', true); await key('Space', false);
  events = await readEvents(); assert.equal(events.at(-1).action, 'UP');
  mark('一键隐藏全部键位后实际长按仍有效');
  await operation('mapping-visibility', { visible: true });
  const hiddenProfile = structuredClone(state.profile); hiddenProfile.bindings[0].visible = false; hiddenProfile.joystick.visible = false;
  await operation('save-profile', { generation: state.generation, profile: hiddenProfile }); await wait(150);
  assert.equal(await win.webContents.executeJavaScript('document.querySelectorAll(".mapping-marker").length'), 1);
  await focusCanvas(); await key('Space', true); await key('W', true);
  events = await readEvents(); assert.equal(events.at(-1).count, 2);
  await key('W', false); await key('Space', false);
  mark('逐个隐藏触点及摇杆后双指映射仍有效');
  await operation('mapping-visibility', { visible: false });
  await operation('editing', { generation: state.generation, enabled: true }); await wait(150);
  assert.equal(await win.webContents.executeJavaScript('document.querySelectorAll(".mapping-marker").length'), 3);
  await operation('editing', { generation: state.generation, enabled: false }); await wait(150);
  assert.equal(await win.webContents.executeJavaScript('document.querySelectorAll(".mapping-marker").length'), 0);
  mark('编辑时显示隐藏键位，结束后恢复隐藏');
  delete hiddenProfile.bindings[0].visible; delete hiddenProfile.joystick.visible;
  await operation('save-profile', { generation: state.generation, profile: hiddenProfile });
  await operation('mapping-visibility', { visible: true });
  await focusCanvas(); await key('Space', true);
  await operation('editing', { generation: state.generation, enabled: true }); await wait(200);
  events = await readEvents(); assert.equal(events.at(-1).active, 0); assert.equal(input.contacts.size, 0);
  mark('进入映射编辑释放长按');
  await key('Space', false); await operation('editing', { generation: state.generation, enabled: false });
  const profile = structuredClone(state.profile); profile.bindings[1].x = .66;
  await operation('save-profile', { generation: state.generation, profile });
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'data/profiles.json')))[state.activePackage].bindings[1].x, .66);
  mark('按应用保存映射到磁盘');
  profile.bindings[1].x = .72; await operation('save-profile', { generation: state.generation, profile });
  await operation('editing', { generation: state.generation, enabled: true });
  await focusCanvas();
  const drag = await win.webContents.executeJavaScript(`(() => {
    const canvas = document.getElementById('screen').getBoundingClientRect();
    const marker = document.querySelectorAll('.mapping-marker')[1].getBoundingClientRect();
    return { x: marker.x + marker.width/2, y: marker.y + marker.height/2,
      endX: canvas.x + canvas.width*.64, endY: canvas.y + canvas.height*.45 };
  })()`);
  const point = (type, x, y) => win.webContents.sendInputEvent({ type, x: Math.round(x), y: Math.round(y), button: 'left', clickCount: 1 });
  point('mouseDown', drag.x, drag.y); await wait(100);
  point('mouseMove', drag.endX, drag.endY); await wait(100);
  point('mouseUp', drag.endX, drag.endY); await wait(500);
  assert.ok(Math.abs(state.profile.bindings[1].x - .64) < .01);
  assert.ok(Math.abs(state.profile.bindings[1].y - .45) < .01);
  await operation('editing', { generation: state.generation, enabled: false });
  await focusCanvas(); await key('F', true); await key('F', false);
  events = await readEvents();
  assert.ok(Math.abs(events.at(-1).pointers[0].x - state.profile.bindings[1].x * 720) < 3);
  mark('界面拖拽触点保存且影响真实 Android 坐标');
  await operation('save-profile', { generation: state.generation, profile });
  await focusCanvas(); await key('F2', true); await key('F2', false);
  const activities = await runtime.adbRun(['shell', 'dumpsys', 'activity', 'activities'], serial);
  assert.ok(activities.split('\n').some(l => /ResumedActivity/.test(l) && /launcher/.test(l)));
  mark('F2 普通快捷键打开 Android 主页');
  await operation('launch', { generation: state.generation, package: 'com.androiddeck.demo' });
  const badApk = path.join(root, 'data/invalid-test.apk'); fs.writeFileSync(badApk, 'invalid apk');
  await assert.rejects(operation('install-path', { generation: state.generation, path: badApk })); fs.unlinkSync(badApk);
  mark('无效 APK 安装失败可恢复');
  await operation('rotate', { generation: state.generation }); await wait(1800);
  let d = await win.webContents.executeJavaScript('window.deckDiagnostics'); assert.ok(d.width > d.height);
  assert.equal(state.activePackage, 'com.androiddeck.demo');
  mark('横屏视频与坐标更新', d);
  await operation('rotate', { generation: state.generation }); await wait(1800);
  await operation('launch', { generation: state.generation, package: 'com.androiddeck.demo' });
  await focusCanvas(); await key('F', true); await key('F', false);
  events = await readEvents(); assert.equal(events.at(-1).active, 0);
  mark('旋转并重连后触控仍可用');
  await operation('reconnect'); await wait(1500);
  assert.equal(state.status, 'ready');
  assert.equal(state.activePackage, 'com.androiddeck.demo');
  mark('屏幕连接重建');
  const forwards = await runtime.adbRun(['forward', '--list']);
  assert.equal(forwards.split('\n').filter(l => l.startsWith(serial + ' ')).length, 1);
  mark('重连不遗留 ADB 转发');
  const until = async predicate => {
    for (let attempt = 0; attempt < 80; attempt++) { if (await predicate()) return; await wait(100); }
    throw new Error('窗口状态更新超时');
  };
  await focusCanvas(); await key('Space', true);
  await win.webContents.executeJavaScript('document.getElementById("fullscreen").click()');
  await until(() => win.isFullScreen() && state.fullscreen && !state.fullscreenChanging);
  assert.equal(input.contacts.size, 0);
  assert.equal(await win.webContents.executeJavaScript('getComputedStyle(document.querySelector(".sidebar")).display'), 'none');
  await key('Space', false); await focusCanvas(); await key('F', true); await key('F', false);
  events = await readEvents(); assert.ok(Math.abs(events.at(-1).pointers[0].x - state.profile.bindings[1].x * 720) < 3);
  mark('工具栏全屏释放长按并保持真实触点坐标');
  await focusCanvas(); await key('Escape', true); await key('Escape', false);
  await until(() => !win.isFullScreen() && !state.fullscreen && !state.fullscreenChanging);
  assert.ok((await runtime.adbRun(['shell', 'dumpsys', 'activity', 'activities'], serial)).split('\n').some(l => /ResumedActivity/.test(l) && /TouchLab/.test(l)));
  mark('Esc 退出全屏且不误触 Android 返回');
  await focusCanvas(); await key('F11', true); await key('F11', false);
  await until(() => win.isFullScreen() && state.fullscreen && !state.fullscreenChanging);
  const fullImage = await win.webContents.capturePage(); fs.writeFileSync(path.join(root, 'data/verified-fullscreen.png'), fullImage.toPNG());
  await focusCanvas(); await key('F11', true); await key('F11', false);
  await until(() => !win.isFullScreen() && !state.fullscreen && !state.fullscreenChanging);
  mark('F11 进入和退出原生全屏');
  win.setFullScreen(true); await until(() => state.fullscreen);
  win.setFullScreen(false); await until(() => !state.fullscreen);
  mark('原生窗口全屏事件同步界面状态');
  const probe = path.join(root, 'data/restart-probe.txt'); fs.writeFileSync(probe, 'installed-app-data-preserved');
  const guestProbe = '/sdcard/Android/data/com.androiddeck.demo/files/restart-probe.txt';
  await runtime.adbRun(['push', probe, guestProbe], serial);
  const gamePath = await runtime.adbRun(['shell', 'pm', 'path', 'com.tencent.tmgp.dnf'], serial);
  const applyMemoryUI = async ramMb => {
    await win.webContents.executeJavaScript(`(() => {
      document.getElementById('memory-settings').click();
      document.querySelector('input[name="ram"][value="${ramMb}"]').checked=true;
      document.getElementById('memory-apply').click();
    })()`);
    for (let attempt = 0; attempt < 150; attempt++) {
      if (state.status === 'ready' && runtime.runningRamMb === ramMb && state.activePackage === 'com.androiddeck.demo') {
        serial = state.serial; await wait(500); return;
      }
      await wait(500);
    }
    throw new Error(`运存 ${ramMb} MiB 重新启动超时`);
  };
  await applyMemoryUI(8192); const eightMemory = await actualMemory();
  assert.ok(eightMemory > 7 * 1024 * 1024);
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'data/settings.json'))).ramMb, 8192);
  assert.equal(await runtime.adbRun(['shell', 'cat', guestProbe], serial), 'installed-app-data-preserved');
  assert.equal(await runtime.adbRun(['shell', 'pm', 'path', 'com.tencent.tmgp.dnf'], serial), gamePath);
  mark('界面选择 8 GB 真实重启，保留 APK、数据及当前映射', { configuredMiB: 8192, actualKiB: eightMemory });
  await applyMemoryUI(6144); const sixMemory = await actualMemory();
  assert.ok(sixMemory > 4 * 1024 * 1024);
  assert.equal(await runtime.adbRun(['shell', 'cat', guestProbe], serial), 'installed-app-data-preserved');
  assert.equal(state.activePackage, 'com.androiddeck.demo');
  mark('界面切回 6 GB 真实生效并保留应用选择', { configuredMiB: 6144, actualKiB: sixMemory });
  await operation('launch', { generation: state.generation, package: 'com.androiddeck.demo' });
  await wait(1000);
  const image = await win.webContents.capturePage(); fs.writeFileSync(path.join(root, 'data/verified-desktop.png'), image.toPNG());
  fs.writeFileSync(path.join(root, 'data/android-touch-events.json'), JSON.stringify(events, null, 2));
  if (!process.argv.includes('--keep-open')) {
    await operation('stop'); assert.ok(!(await runtime.devices()).some(d => d.serial === serial));
    assert.ok(!(await runtime.adbRun(['forward', '--list'])).includes(serial + ' '));
    mark('关闭本应用设备并清理转发');
  }
  fs.writeFileSync(path.join(root, 'data/integration-report.json'), JSON.stringify({ time: new Date().toISOString(), results }, null, 2));
};
